import type { MetadataRoute } from "next";
import { devTools } from "@/data/devTools";
import { PDF_TOOLS } from "@/data/pdfTools";
import { SITE_URL, absoluteUrl } from "@/lib/site";

export const dynamic = "force-static";

/**
 * Build-time snapshot of every canonical, indexable public URL:
 * homepage, both category hubs, all 63 tool pages and the trust pages.
 * Admin/API/temporary processing URLs never appear here — they are either
 * gated behind /api/ or don't exist as crawlable routes.
 *
 * `lastModified` is the build timestamp (an accurate, monotonic date); the
 * sitemap is regenerated by rebuilding after real content changes.
 */
export default function sitemap(): MetadataRoute.Sitemap {
  const buildDate = new Date();

  const staticRoutes: MetadataRoute.Sitemap = (
    [
      // Root canonical is the bare origin (no trailing slash) for consistency.
      { url: SITE_URL, changeFrequency: "weekly" as const, priority: 1 },
      { url: absoluteUrl("/developer-tools"), changeFrequency: "weekly" as const, priority: 0.9 },
      { url: absoluteUrl("/tools/pdf"), changeFrequency: "weekly" as const, priority: 0.9 },
      ...["/about", "/contact", "/privacy", "/terms"].map((path) => ({
        url: absoluteUrl(path),
        changeFrequency: "monthly" as const,
        priority: 0.3,
      })),
    ]
  ).map((entry) => ({ ...entry, lastModified: buildDate }));

  const toolRoutes: MetadataRoute.Sitemap = [
    ...devTools.map((tool) => ({
      url: absoluteUrl(`/tools/${tool.slug}`),
      lastModified: buildDate,
      changeFrequency: "monthly" as const,
      priority: tool.slug === "json-formatter" ? 0.9 : 0.7,
    })),
    ...PDF_TOOLS.map((tool) => ({
      url: absoluteUrl(`/tools/${tool.slug}`),
      lastModified: buildDate,
      changeFrequency: "monthly" as const,
      priority: tool.slug === "merge-pdf" || tool.slug === "compress-pdf" ? 0.9 : 0.7,
    })),
  ];

  return [...staticRoutes, ...toolRoutes];
}
